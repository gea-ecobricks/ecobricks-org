				<p data-lang-id="007-third-page-paragraph">
				Making an OEB is super simple.  It doesn't require any special skils or machines! When many are collected, a range of applications await. OEBs can be used to make make <a href="/modules">modular</a> furniture.  However they are especially suited for building green spaces using <a href ="earth-methods.php">earth building techniques</a> and <a href ="earth.php">principles.</a></p>
