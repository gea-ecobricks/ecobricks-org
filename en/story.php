				<p data-lang-id="005-first-page-paragraph">The GEA was born in the green valley of the Chico River, in the traditional territory of the Igorot people (<i>Kaigorotan</i>) of the Northern Philippine Cordilleras. Guided by their <a href="/ayyew">Ayyew</a> ethos and regenerative principles, we became convinced that truly solving plastic requires a new and careful relationship with the petro-capital economy. So we established the GEA as a not-for-profit <a href="about.php#block2">Earth Enterprise</a>&mdash; free to maintain global standards for ecobricking and plastic sequestration without a profit motive, and instead with a full focus on Earth service.</p>
