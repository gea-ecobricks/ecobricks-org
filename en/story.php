    <p data-lang-id="022-block1-p2">The development of ecobrick concepts was deeply influenced by Igorot principles. Inspired by a stone rice-terrace wall that had collapsed in a storm and was rebuilt using the very same stones, Russell and Irene were determined that ecobrick constructions should also be reusable over and over again. Inspired by the concept of <a href="/ayyew" data-lang-id="023-block1-link1">Ayyew</a>, the team prioritized using ecobricks for building green spaces that would enrich neighbourhoods and schools.</p>

    <p data-lang-id="024-block1-p3">With the launch of <a href="index.php">Ecobricks.org</a> in 2013, the Filipino ecobrick movement discovered that people around the world&mdash; desperate for a simple solution to plastic&mdash; had begun ecobricking independently. After making contact with movement leaders in South Africa and North and Central America, it was decided to form an alliance to establish consistency across the growing global movement. Spearheaded by Russell Maier, Jo Stodgel (Upcycle Santa Fe), Candice Mostert, Patricia Acuna and Irene Bakisan, the Global Ecobrick Alliance (GEA) was formed alongside the Vision Ecobrick Guidebook v2.0. In 2014, with the support of Ian Domisse, founder of the Ecobrick Exchange in South Africa, the alliance agreed to use the non-hyphenated, lower-case term <b>&ldquo;ecobrick&rdquo;</b> as the standardized term across all materials&mdash; so that ecobrickers everywhere could rally around one word, one hashtag, and one search term.</p>

